export const LOCALES = { en, he };

const STORAGE_KEY = 'agilevow.lang';
const has = (object, key) => Object.prototype.hasOwnProperty.call(object, key);

// English unless Hebrew was chosen: ?lang= in the URL, or the choice the language picker remembered. The browser's own
// language is deliberately not consulted, so nobody gets a language they did not pick.
function resolveLocale() {
  try {
    const asked = new URLSearchParams(globalThis.location.search).get('lang');
    if (asked && has(LOCALES, asked)) return asked;
  } catch { /* No location, or an unreadable query. */ }
  try {
    const saved = globalThis.localStorage.getItem(STORAGE_KEY);
    if (saved && has(LOCALES, saved)) return saved;
  } catch { /* Storage can be disabled or throw. */ }
  return 'en';
}

export const locale = resolveLocale();

// Active language, then English, then the key itself. Never throws.
export function t(key, vars) {
  let text = has(LOCALES[locale], key) ? LOCALES[locale][key] : has(LOCALES.en, key) ? LOCALES.en[key] : key;
  if (vars && typeof vars === 'object' && typeof text === 'string') {
    text = text.replace(/\{(\w+)\}/g, (whole, name) => (has(vars, name) && vars[name] != null ? String(vars[name]) : whole));
  }
  return text;
}

// Sets <html lang dir> and translates every element that names a key. The English text written in the HTML
// stays in place for a key nobody defined, so a missing string never shows up as a raw key.
export function applyDocumentLocale() {
  const root = document.documentElement;
  root.lang = locale;
  root.dir = locale === 'he' ? 'rtl' : 'ltr';
  const translate = (attribute, apply) => {
    for (const node of document.querySelectorAll(`[${attribute}]`)) {
      const key = node.getAttribute(attribute);
      const text = t(key);
      if (text !== key) apply(node, text);
    }
  };
  translate('data-i18n', (node, text) => { node.textContent = text; });
  translate('data-i18n-placeholder', (node, text) => { node.setAttribute('placeholder', text); });
  translate('data-i18n-aria-label', (node, text) => { node.setAttribute('aria-label', text); });
  translate('data-i18n-title', (node, text) => { node.setAttribute('title', text); });
}
